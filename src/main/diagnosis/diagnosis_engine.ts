// ─── Storage paths ────────────────────────────────────────────────────────────

function diagnosisDir(): string {
  const d = join(app.getPath('userData'), 'substrate', 'diagnosis');
  if (!existsSync(d)) mkdirSync(d, { recursive: true });
  return d;
}

// D-BP202-BM02-007: `id` is caller-supplied (locally generated by generateDiagnosisId() below,
// OR received verbatim off the LAN from a peer's /api/diagnosis/post|answer|upvote body -- see
// peer_server.ts's resolveSignedDiagnosisRequest) and becomes a FILENAME via diagnosisPath()/
// verifiedEbletPath() below. This is a path-traversal surface SEPARATE from the auth question:
// even a signature-verified caller must not be able to write/read outside the diagnosis
// directory via a crafted id ("..\\..\\Windows\\System32\\evil", "C:\\Windows\\evil", a bare
// drive letter, a UNC prefix, NTFS ADS ("name:stream"), trailing dot/space Windows quirks, etc).
// Rather than trying to enumerate and strip every unsafe character, this is a closed ALLOWLIST:
// only ASCII letters, digits, underscore and hyphen, 1-128 chars. Anything else is REFUSED
// outright (never silently stripped -- stripping two different unsafe ids down to the same
// sanitized string would let one caller silently overwrite another's file). This is the single
// choke point both diagnosisPath() and verifiedEbletPath() call through, so every read and every
// write in this module is covered regardless of which exported function let the id in.
export class UnsafeDiagnosisIdError extends Error {
  constructor(id: unknown) {
    super(`unsafe diagnosis id rejected (path-traversal guard, D-BP202-BM02-007): ${JSON.stringify(id)}`);
    this.name = 'UnsafeDiagnosisIdError';
  }
}

const SAFE_DIAGNOSIS_ID_RE = /^[A-Za-z0-9_-]{1,128}$/;

export function isSafeDiagnosisId(id: unknown): id is string {
  return typeof id === 'string' && SAFE_DIAGNOSIS_ID_RE.test(id);
}

function assertSafeDiagnosisId(id: string): void {
  if (!isSafeDiagnosisId(id)) throw new UnsafeDiagnosisIdError(id);
}

function diagnosisPath(id: string): string {
  assertSafeDiagnosisId(id);
  return join(diagnosisDir(), `diagnosis_${id}.json`);
}

function verifiedEbletPath(id: string): string {
  assertSafeDiagnosisId(id);
  const d = join(app.getPath('userData'), 'substrate');
  if (!existsSync(d)) mkdirSync(d, { recursive: true });
  return join(d, `diagnosis_verified_${id}.json`);
}

// ─── D-BP202-BM02-007 Part B: read-back / integrity check ─────────────────────
//
// Lets a sender confirm an artifact actually landed on a peer instead of trusting an HTTP 200
// that (before this dispatch) was returned unconditionally regardless of write success -- see
// peer_server.ts's /api/diagnosis/verify route and diagnosis_ipc.ts's onDiagnosisVerify hook.
// Deliberately returns ONLY existence + integrity figures, never the stored content itself, so
// this cannot be used as a substrate-content exfiltration read primitive.
export interface DiagnosisArtifactCheck {
  exists: boolean;
  byteLength: number | null;
  sha256: string | null;
}

export async function checkDiagnosisArtifact(id: string): Promise<DiagnosisArtifactCheck> {
  try {
    const path = diagnosisPath(id); // throws UnsafeDiagnosisIdError on a bad id -- caught below
    if (!existsSync(path)) return { exists: false, byteLength: null, sha256: null };
    const buf = readFileSync(path);
    return { exists: true, byteLength: buf.length, sha256: sha256hex(buf.toString('utf8')) };
  } catch {
    // Unsafe id or any read error: report "does not exist" rather than leak WHY (an unsafe id
    // and a genuinely-missing id both read as "not found" to the caller -- fail closed).
    return { exists: false, byteLength: null, sha256: null };
  }
}

// ─── Helpers ──────────────────────────────────────────────────────────────────

function generateDiagnosisId(): string {
  return randomBytes(8).toString('hex');
}

function sha256hex(s: string): string {
  return createHash('sha256').update(s).digest('hex');
}

// ─── Core CRUD ────────────────────────────────────────────────────────────────

export async function createDiagnosis(input: DiagnosisCreateInput): Promise<string> {
  const id = generateDiagnosisId();
  const posterId = getUserId();

  const saltLevel = input.saltLevel ?? 'preserved_open';
  const saltCfg = SALT_LEVEL_CONFIGS[saltLevel];
  const noAutoExpiry = saltLevel === 'preserved_forever';

  const post: DiagnosisPost = {
    id,
    question: input.question,
    domain: input.domain,
    context: input.context,
    priorAttempts: input.priorAttempts,
    bounty: input.bounty,
    visibility: input.visibility,
    saltLevel,
    noAutoExpiry,
    posterId,
    posterName: input.posterName ?? 'Anonymous',
    timestamp: Date.now(),
    status: 'open',
    answers: [],
    source: input.source ?? 'manual',
  };

  writeFileSync(diagnosisPath(id), JSON.stringify(post, null, 2), 'utf8');
  console.log(`[DiagnosisEngine] Created diagnosis id=${id} domain=${input.domain} saltLevel=${saltLevel}`);

  // v0.4.1: schedule Catacomb relocation for preserved_forever
  if (saltLevel === 'preserved_forever' && saltCfg.autoExpiry) {
    import('./catacomb_migrator').then(({ scheduleCatacombRelocation }) => {
      scheduleCatacombRelocation(id, saltCfg.autoExpiry!).catch((err) =>
        console.error('[DiagnosisEngine] Catacomb schedule error:', err),
      );
    }).catch(() => { /* non-fatal */ });
  }

  // Broadcast to Constellation peers (non-blocking)
  broadcastDiagnosis(post).catch((err) =>
    console.error('[DiagnosisEngine] Broadcast error:', err),
  );

  return id;
}

export async function loadDiagnosis(id: string): Promise<DiagnosisPost | null> {
  try {
    const path = diagnosisPath(id);
    if (!existsSync(path)) return null;
    return JSON.parse(readFileSync(path, 'utf8')) as DiagnosisPost;
  } catch {
    return null;
  }
}

export async function listDiagnoses(filter?: { status?: string; domain?: DiagnosisDomain }): Promise<DiagnosisPost[]> {
  try {
    const dir = diagnosisDir();
    const files = readdirSync(dir).filter((f) => f.startsWith('diagnosis_') && f.endsWith('.json'));
    const posts: DiagnosisPost[] = [];
    for (const f of files) {
      try {
        const post = JSON.parse(readFileSync(join(dir, f), 'utf8')) as DiagnosisPost;
        if (filter?.status && post.status !== filter.status) continue;
        if (filter?.domain && post.domain !== filter.domain) continue;
        posts.push(post);
      } catch { /* skip corrupted file */ }
    }
    return posts.sort((a, b) => b.timestamp - a.timestamp);
  } catch {
    return [];
  }
}

export async function saveDiagnosis(post: DiagnosisPost): Promise<void> {
  writeFileSync(diagnosisPath(post.id), JSON.stringify(post, null, 2), 'utf8');
}

// ─── Answer submission ────────────────────────────────────────────────────────

export async function submitAnswer(
  diagnosisId: string,
  answerText: string,
  sources: string[],
  credentials?: string,
): Promise<string | null> {
  const post = await loadDiagnosis(diagnosisId);
  if (!post) return null;

  const answerId = generateDiagnosisId();
  const responderId = getUserId();

  const answer: DiagnosisAnswer = {
    id: answerId,
    diagnosisId,
    responderId,
    answerText,
    sources,
    credentials,
    timestamp: Date.now(),
    upvotes: 0,
  };

  post.answers.push(answer);
  if (post.status === 'open') post.status = 'answered';
  await saveDiagnosis(post);

  // Broadcast answer back to poster (non-blocking)
  broadcastAnswer(post, answer).catch((err) =>
    console.error('[DiagnosisEngine] Answer broadcast error:', err),
  );

  return answerId;
}

export async function upvoteAnswer(diagnosisId: string, answerId: string): Promise<void> {
  const post = await loadDiagnosis(diagnosisId);
  if (!post) return;
  const answer = post.answers.find((a) => a.id === answerId);
  if (answer) {
    answer.upvotes++;
    await saveDiagnosis(post);
  }
}

// ─── Accept answer + bounty + substrate write ─────────────────────────────────

export async function acceptAnswer(diagnosisId: string, answerId: string): Promise<boolean> {
  const post = await loadDiagnosis(diagnosisId);
  if (!post) return false;

  const answer = post.answers.find((a) => a.id === answerId);
  if (!answer) return false;

  post.acceptedAnswerId = answerId;
  post.status = 'resolved';
  await saveDiagnosis(post);

  // Write verified eblet to substrate
  await writeVerifiedEblet(post, answer);

  // Payout bounty
  const { payoutBounty } = await import('./bounty_substitution');
  await payoutBounty(post.bounty, post.posterId, answer.responderId);

  console.log(`[DiagnosisEngine] Accepted answer=${answerId} for diagnosis=${diagnosisId}`);
  return true;
}

// ─── Substrate write-back ─────────────────────────────────────────────────────

export async function writeVerifiedEblet(post: DiagnosisPost, answer: DiagnosisAnswer): Promise<void> {
  const content = {
    diagnosisId: post.id,
    question: post.question,
    domain: post.domain,
    answer: answer.answerText,
    sources: answer.sources,
    credentials: answer.credentials ?? null,
    resolvedAt: Date.now(),
    provenance: `diagnosis_verified:${post.id}:${answer.responderId}:bp083`,
    verified: true,
    sha256: sha256hex(post.question + answer.answerText),
  };

  writeFileSync(verifiedEbletPath(post.id), JSON.stringify(content, null, 2), 'utf8');

  // Also write to substrate API if available
  try {
    const { writeVerifiedEblet } = await import('../mnem_eblet_store');
    const { createHash } = await import('crypto');
    const q = `[Diagnosis:${post.domain}] ${post.question.slice(0, 120)}`;
    const a = answer.answerText.slice(0, 600);
    await writeVerifiedEblet({
      question: q,
      answer: a,
      provenance: `diagnosis:${post.id}`,
      verified: true,
      sha256: createHash('sha256').update(q + a).digest('hex'),
      timestamp: Date.now(),
    });
  } catch { /* non-fatal */ }

  console.log(`[DiagnosisEngine] Verified eblet written for diagnosis=${post.id}`);
}

// ─── Federation: broadcast/receive ───────────────────────────────────────────

// D-BP202-BM02-012: builds the signed_frame request body peer_server.ts's
// resolveSignedDiagnosisRequest expects, or the legacy flat body if local signing fails soft.
// `dispatchPayload` carries sender_peer_id INSIDE the signed frame (same shape mic_dispatcher.ts
// uses for /api/plow-domain) so the receiver can prefer a previously-learned key over the
// self-declared one embedded in the same frame (trust-on-first-use fallback only).
function buildSignedDiagnosisRequestBody(innerPayload: Record<string, unknown>): Record<string, unknown> {
  const dispatchPayload = { ...innerPayload, sender_peer_id: getStablePeerId() };
  const signed = signAnnouncePayload(dispatchPayload.sender_peer_id, dispatchPayload);
  // signAnnouncePayload fails soft (returns null) only on a LOCAL signing problem (e.g. the
  // Thorax keypair is unreadable) -- see announce_frame.ts's own doc comment. This is NOT a
  // peer-version decision: the sender never inspects a target's declared version/capability to
  // decide whether to sign. See this dispatch's MIXED-VERSION DECISION for why a version-based
  // downgrade path was deliberately not added here.
  return signed ? { signed_frame: signed.signedHex } : dispatchPayload;
}

export async function broadcastDiagnosis(post: DiagnosisPost): Promise<void> {
  if (post.visibility === 'lan') return; // LAN-only: don't broadcast

  // SCAFFOLD v0.4.0: broadcast to Constellation peers via peer_server HTTP
  try {
    const { discoverPeers } = await import('../federation/constellation_discovery');
    const peers = await discoverPeers();
    const onlinePeers = peers.filter((p) => p.online);

    const requestBody = buildSignedDiagnosisRequestBody(post as unknown as Record<string, unknown>);

    await Promise.allSettled(
      onlinePeers.map((peer) =>
        fetch(`http://${peer.address}/api/diagnosis/post`, {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify(requestBody),
          signal: AbortSignal.timeout(5000),
        }),
      ),
    );
  } catch { /* non-fatal */ }
}

export async function receiveDiagnosis(post: DiagnosisPost): Promise<void> {
  // Received from a Constellation peer — save locally
  const existing = await loadDiagnosis(post.id);
  if (existing) return; // Already have it

  writeFileSync(diagnosisPath(post.id), JSON.stringify(post, null, 2), 'utf8');
  console.log(`[DiagnosisEngine] Received diagnosis id=${post.id} from peer`);
}

async function broadcastAnswer(post: DiagnosisPost, answer: DiagnosisAnswer): Promise<void> {
  // SCAFFOLD v0.4.0: send answer back to poster's peer
  // In production: Thorax-encrypted Socceri transport
  try {
    const { discoverPeers } = await import('../federation/constellation_discovery');
    const peers = await discoverPeers();
    const posterPeer = peers.find((p) => p.id === post.posterId);
    if (!posterPeer?.online) return;

    // D-BP202-BM02-012: same signed-frame wrapping as broadcastDiagnosis() above.
    const requestBody = buildSignedDiagnosisRequestBody({ diagnosisId: post.id, answer } as unknown as Record<string, unknown>);

    await fetch(`http://${posterPeer.address}/api/diagnosis/answer`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(requestBody),
      signal: AbortSignal.timeout(5000),
    });
  } catch { /* non-fatal */ }
}

// D-BP202-BM02-012 Part B: sender-side counterpart to peer_server.ts's /api/diagnosis/verify
// route (D-BP202-BM02-007 Part B). Lets a sender confirm a post/answer it just broadcast
// actually landed on a peer instead of trusting an unconditional 200 -- "sent" only becomes
// "proved" once this read-back matches. Same signed-frame discipline as the writes above; the
// verify route itself never returns stored content, only existence/byteLength/sha256.
export interface RemoteDiagnosisVerifyResult {
  ok: boolean;
  status: number;
  exists?: boolean;
  byteLength?: number | null;
  sha256?: string | null;
  error?: string;
}

export async function verifyDiagnosisArtifactOnPeer(
  peerAddress: string,
  id: string,
): Promise<RemoteDiagnosisVerifyResult> {
  try {
    const requestBody = buildSignedDiagnosisRequestBody({ id });
    const res = await fetch(`http://${peerAddress}/api/diagnosis/verify`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(requestBody),
      signal: AbortSignal.timeout(5000),
    });
    const data = await res.json().catch(() => ({}) as Record<string, unknown>);
    if (!res.ok) {
      return { ok: false, status: res.status, error: typeof data.error === 'string' ? data.error : `HTTP ${res.status}` };
    }
    return {
      ok: true,
      status: res.status,
      exists: Boolean((data as { exists?: unknown }).exists),
      byteLength: (data as { byteLength?: number | null }).byteLength ?? null,
      sha256: (data as { sha256?: string | null }).sha256 ?? null,
    };
  } catch (err) {
    return { ok: false, status: 0, error: err instanceof Error ? err.message : String(err) };
  }
}

export async function receiveAnswer(diagnosisId: string, answer: DiagnosisAnswer): Promise<void> {
  const post = await loadDiagnosis(diagnosisId);
  if (!post) return;
  if (post.answers.some((a) => a.id === answer.id)) return; // Deduplicate

  post.answers.push(answer);
  if (post.status === 'open') post.status = 'answered';
  await saveDiagnosis(post);
}

// ─── Helper: get local user ID ────────────────────────────────────────────────

function getUserId(): string {
  try {
    const id = localStorage?.getItem?.('mnemo_lb_user_id');
    if (id) return id;
  } catch { /* renderer context only */ }
  // Main process fallback: use machine-stable ID from federation peer-discovery
  return 'local-user';
}
